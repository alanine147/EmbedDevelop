void Led_System_Running(void)
{
    static boolean ledOn = TRUE;
    if (TRUE == ledOn)
    {
        HAL_GPIO_WritePin(GPIOC, GPIO_PIN_13, GPIO_PIN_SET);
        ledOn = FALSE;
        // sys_log("led opens");
    }
    else
    {
        HAL_GPIO_WritePin(GPIOC, GPIO_PIN_13, GPIO_PIN_RESET);
        ledOn = TRUE;
    }
}


