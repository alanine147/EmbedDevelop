RealClockTimeType TimeNowGet(void)
{
    RealClockTimeType timeCur = {0u};
    uint32 ticks = HAL_GetTick();
    timeCur.microSec = ticks % 1000u;
    timeCur.sec = ticks / 1000u;
    return timeCur;
}


